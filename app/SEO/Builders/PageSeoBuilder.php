<?php

declare(strict_types=1);

namespace App\SEO\Builders;

use App\SEO\DTO\SeoData;

class PageSeoBuilder
{
    public function build(
        string $route,
        string $title,
        string $description,
        array $keywords = [],
        array $breadcrumbs = [],
        string $robots = 'index, follow'
    ): SeoData {
        $url = route($route);

        return new SeoData(
            /*
            |--------------------------------------------------------------------------
            | SEO básico
            |--------------------------------------------------------------------------
            */
            title: $title,
            description: $description,

            /*
            |--------------------------------------------------------------------------
            | OpenGraph
            |--------------------------------------------------------------------------
            */
            image: config('site.og_image', asset('images/logo.png')),
            imageAlt: config('app.name'),

            /*
            |--------------------------------------------------------------------------
            | URLs
            |--------------------------------------------------------------------------
            */
            url: $url,
            canonical: $url,

            /*
            |--------------------------------------------------------------------------
            | Tipo de página
            |--------------------------------------------------------------------------
            */
            type: 'website',

            /*
            |--------------------------------------------------------------------------
            | Keywords
            |--------------------------------------------------------------------------
            */
            keywords: $keywords,

            /*
            |--------------------------------------------------------------------------
            | Robots
            |--------------------------------------------------------------------------
            */
            robots: $robots,

            /*
            |--------------------------------------------------------------------------
            | Breadcrumbs
            |--------------------------------------------------------------------------
            */
            breadcrumbs: $breadcrumbs ?: [
                [
                    'name' => 'Home',
                    'url' => route('home'),
                ],
                [
                    'name' => $title,
                    'url' => $url,
                ],
            ],
        );
    }
}
